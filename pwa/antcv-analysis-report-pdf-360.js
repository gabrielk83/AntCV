  // ---- print via a hidden iframe (client-side "Save as PDF") -----------------
  function exportPdf(btn) {
    var t = T();
    var m = model(readRationale(), readMeta(), readPersonalInfo());
    if (!hasAnalysis(m)) { window.alert(t.noData); return; }
    var label = btn ? btn.textContent : '';
    if (btn) { btn.disabled = true; btn.textContent = isDanish() ? 'Forbereder…' : 'Preparing…'; }

    loadIconDataUrl().then(function (icon) {
      var html = reportHtml(m, icon);
      var iframe = document.createElement('iframe');
      iframe.setAttribute('aria-hidden', 'true');
      iframe.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0;visibility:hidden;';
      document.body.appendChild(iframe);

      var done = false;
      function cleanup() {
        if (done) return; done = true;
        setTimeout(function () { if (iframe && iframe.parentNode) iframe.parentNode.removeChild(iframe); }, 1200);
        if (btn) { btn.disabled = false; btn.textContent = label || t.download; }
      }

      var doc = iframe.contentWindow.document;
      doc.open(); doc.write(html); doc.close();

      function go() {
        try {
          var win = iframe.contentWindow;
          win.focus();
          if (win.matchMedia) {
            var mql = win.matchMedia('print');
            var handler = function (e) { if (!e.matches) { mql.removeListener(handler); cleanup(); } };
            try { mql.addListener(handler); } catch (_) {}
          }
          win.onafterprint = cleanup;
          win.print();
          // Fallback cleanup if onafterprint never fires (some browsers).
          setTimeout(cleanup, 60000);
        } catch (e) {
          cleanup();
          window.alert((isDanish() ? 'Kunne ikke åbne printdialogen: ' : 'Could not open the print dialog: ') + (e && e.message || e));
        }
      }

      // Wait a tick for layout + the (already-inlined) icon to settle.
      if (iframe.contentWindow.document.readyState === 'complete') setTimeout(go, 150);
      else iframe.onload = function () { setTimeout(go, 150); };
    });
  }

