/* AntCV Analysis report — panel enhancement + branded PDF export (v1.50.146)
 * ============================================================================
 *
 * Goal (owner request)
 * --------------------
 * 1. ENHANCE the in-app Analysis panel with three new, honesty-first blocks:
 *      - Assumptions          (working assumptions the briefing makes)
 *      - Confidence review    (low- + medium-confidence statements, banded)
 *      - Recommendations      (concrete, honest next actions)
 * 2. Let the user DOWNLOAD the analysis as a branded PDF. The export carries:
 *      - the AntCV icon + wordmark + slogan (masthead)
 *      - the application name (role — company) + candidate name
 *      - the date + application name in the footer
 *      - assumptions, low/medium-confidence statements, recommendations
 *      - an AI watermark (diagonal "AI-ASSISTED" wash) + a closing AI notice.
 *
 * Data source
 * -----------
 * The Analysis panel is rendered by app.js from the `rationale` localStorage
 * object (the `yo` object). The new fields (assumptions, recommendations,
 * confidence_notes) are produced by the SAME analysis pass — see
 * workers/proxy/src/jd-analysis.js (and demo-proxy) — and merged into
 * `rationale` by antcv-analysis-panel-jd-block-356.js / antcv-analysis-merge-344.js.
 * This sidecar only READS `rationale` + `meta` + `personalInfo`; it never calls
 * the network and never edits app.js.
 *
 * Confidence bands follow the owner-locked spec (FEATURE-CONF-001,
 * docs/design/Verification_Confidence_Section.md):
 *      low    : confidence < 0.4   (reddish)
 *      medium : 0.4 <= conf < 0.7  (amber)
 *      high   : confidence >= 0.7  (untinted; not shown in the review block)
 *
 * Discipline: additive sidecar, idempotent, removable in one <script> line.
 * Reuses the panel finder exposed by antcv-analysis-panel-jd-block-356.js.
 */
