  // TOP block: Assumptions + Recommendations — owner 2026-06-09: these belong in
  // the UPPER part of the panel, just below "Overall Fit" (the summary), not buried
  // in the bottom EXPORT & DETAIL block. Returns null when neither is present.
  function buildTopBlock() {
    var t = T();
    var m = model(readRationale(), readMeta(), readPersonalInfo());
    if (!hasAnalysis(m) || (!m.assumptions.length && !m.recommendations.length)) return null;
    var wrap = document.createElement('div');
    wrap.id = TOP_BLOCK_ID;
    if (m.assumptions.length) _group(wrap, t.assumptions, '#283556', function (g) { g.appendChild(_list(m.assumptions)); });
    if (m.recommendations.length) _group(wrap, t.recommendations, '#00746E', function (g) { g.appendChild(_list(m.recommendations)); });
    return wrap;
  }

  // BOTTOM block: Confidence review THEN the EXPORT & DETAIL row (heading +
  // download). Owner 2026-06-09: Confidence Review sits ABOVE the download button.
  function buildBlock() {
    var t = T();
    var m = model(readRationale(), readMeta(), readPersonalInfo());
    var wrap = document.createElement('div');
    wrap.id = BLOCK_ID;

    if (hasAnalysis(m) && (m.confLow.length || m.confMedium.length)) {
      _group(wrap, t.confidence, '#283556', function (g) {
        function band(items, cls, label) {
          if (!items.length) return;
          var box = document.createElement('div'); box.className = 'arx-conf ' + cls;
          var bh = document.createElement('div'); bh.style.cssText = 'font-weight:700;font-size:10px;margin-bottom:3px;'; bh.textContent = label;
          box.appendChild(bh);
          var ul = document.createElement('ul');
          items.forEach(function (c) {
            var li = document.createElement('li');
            li.textContent = c.text;
            var sm = document.createElement('small');
            sm.textContent = ' (' + Math.round(c.conf * 100) + '%' + (c.issue ? ' — ' + c.issue : '') + ')';
            li.appendChild(sm); ul.appendChild(li);
          });
          box.appendChild(ul); g.appendChild(box);
        }
        band(m.confLow, 'arx-conf-low', t.low);
        band(m.confMedium, 'arx-conf-medium', t.medium);
      });
    }

    // EXPORT & DETAIL row (heading + download) — now BELOW Confidence Review.
    var row = document.createElement('div');
    row.className = 'arx-row';
    var h = document.createElement('div'); h.className = 'arx-heading'; h.textContent = t.heading;
    // ANALYSE-JD-BUTTON-POS-001 (owner 2026-06-10: "same row, side by side"):
    // an Analyse-JD button lives HERE, next to Download. It delegates the
    // click to the real run button inside the 356 JD block (which hides its
    // own copy while this one exists), so the run logic stays in one place.
    var an = document.createElement('button');
    an.className = 'arx-analyse'; an.type = 'button';
    an.textContent = t.analyse;
    an.addEventListener('click', function () {
      var real = document.querySelector('#antcv-analysis-panel-jd-block .apjb-run');
      if (!real) return;
      real.click();
      // Mirror the real button's busy state (it disables itself while the
      // analysis runs) without coupling to 356's internals.
      an.disabled = true; var was = an.textContent; an.textContent = real.textContent;
      var n = 0;
      var iv = setInterval(function () {
        if (!document.body.contains(real) || !real.disabled || ++n > 300) {
          clearInterval(iv); an.disabled = false; an.textContent = was;
        } else { an.textContent = real.textContent; }
      }, 400);
    });
    var dl = document.createElement('button');
    dl.className = 'arx-dl'; dl.type = 'button'; dl.textContent = t.download;
    dl.addEventListener('click', function () { exportPdf(dl); });
    var btns = document.createElement('div');
    btns.className = 'arx-btns';
    btns.appendChild(an); btns.appendChild(dl);
    row.appendChild(h); row.appendChild(btns);
    wrap.appendChild(row);

    if (!hasAnalysis(m)) {
      var hint = document.createElement('div'); hint.className = 'arx-hint'; hint.textContent = t.noData;
      wrap.appendChild(hint);
    }
    return wrap;
  }

